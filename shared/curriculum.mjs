/**
 * @param {string} domain DOMAINS 中的领域 ID
 * @returns {Curriculum}
 */
export function curriculumFor(domain) {
  const row = Object.hasOwn(CURRICULA, domain) ? CURRICULA[domain] : GENERAL;
  return {
    search: [...row.search],
    outcomes: [...row.outcomes],
    project: row.project,
    checks: [...row.checks],
  };
}

export function isAgentTrainingGoal(text) {
  return /\bagent\b|智能体/i.test(text) && /训练|微调|fine.?tun|\bsft\b/i.test(text)
}
